#pragma once

#include <stdint.h>

/* Product identity shared by the firmware, BLE protocol and documentation.
 *
 * Canonical display name: "墨程CalCal" (no space between the parts).
 * Keep the phone clients, server and docs in sync with these strings. */
#define BRAND_NAME_ZH "墨程"
#define BRAND_NAME_EN "CalCal"
#define BRAND_NAME BRAND_NAME_ZH BRAND_NAME_EN
#define BRAND_SHORT_NAME "CalCal"
/* ASCII alias used for the BLE GAP/advertising name. Some central stacks do
 * not render a UTF-8 device name well, and the mini program scans by this
 * prefix, so the radio keeps the Latin form while the connected device
 * reports BRAND_NAME. */
#define BRAND_DEVICE_NAME "Mochen CalCal"
#define BRAND_TAGLINE "把日程写进墨水屏"
/* Shorter, schedule-oriented line drawn next to BRAND_NAME on the lock
 * screen; the full tagline stays on the cold-boot splash. */
#define BRAND_LOCK_SUBTITLE "墨水屏日程表"
/* The firmware version is deliberately NOT defined here. It lives in the
 * project's version.txt, which ESP-IDF bakes into the image as PROJECT_VER;
 * firmware and phone clients read it back from the app description, so there
 * is exactly one place to bump. */

/* 1-bit, row-major brand bitmap. MSB is the leftmost pixel and a set bit
 * means ink (black) on the panel. The logo bitmaps come from
 * miniprogram/CalCal_logo.png; the wordmark is rendered from BRAND_NAME_ZH +
 * BRAND_NAME_EN. Both are generated by tools/gen_brand_assets.py; do not draw
 * or edit them by hand. */
typedef struct {
  uint16_t width;
  uint16_t height;
  const uint8_t *bits;
} brand_bitmap_t;

/* 200x140 for the cold-boot splash. */
extern const brand_bitmap_t brand_logo_boot;
/* 96x67 for the lock/sleep screen. */
extern const brand_bitmap_t brand_logo_lock;
/* 30x21 for the top bar on the month, day and detail screens; 21 px tall to
 * match the 5x7 scale-3 clock digits. */
extern const brand_bitmap_t brand_logo_header;
/* Compact wordmark for the top bar; generated from BRAND_NAME_ZH + _EN so the
 * brand keeps a proper pixel baseline at a smaller size than the 24 px CJK
 * table. */
extern const brand_bitmap_t brand_wordmark;
/* 248x248 WeChat mini program code shown on the empty lock screen; generated
 * by tools/gen_qrcode.py from miniprogram/miniprogram_qrcode.jpg. */
extern const brand_bitmap_t brand_qrcode;

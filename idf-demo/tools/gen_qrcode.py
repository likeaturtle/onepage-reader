#!/usr/bin/env python3
"""Generate the 1-bit mini-program code embedded in the firmware.

The empty lock screen shows the mini program code so a new user can add events
without a PC. The source is ``miniprogram/miniprogram_qrcode.jpg`` (a WeChat
mini program code, 258x258). The panel is 1-bit, so the JPEG is composited on
white, thresholded and packed into the same layout as the brand logo bitmaps.

The JPEG's white border is cropped away symmetrically: on the panel the white
canvas around the bitmap is the quiet zone the scanner needs, so the bitmap
only has to carry the ink.

Outputs ``components/brand/src/brand_qrcode.c`` (committed) and
``tools/preview_qrcode.png`` (ignored, for an eye check). Rerun after the
mini program code or its link changes:

    /Users/fujd/.espressif/tools/python/v6.1/venv/bin/python tools/gen_qrcode.py

Requires Pillow (available in the ESP-IDF virtualenv). The threshold is shared
with tools/gen_brand_assets.py (160) so both asset sets ink the same edges.
"""

import argparse
import pathlib
import sys

try:
    from PIL import Image
except ImportError:  # pragma: no cover - host dependency
    sys.exit("needs Pillow: use the ESP-IDF virtualenv python")

from gen_brand_assets import INK_THRESHOLD, emit_array, pack_pixels

REPO = pathlib.Path(__file__).resolve().parent.parent
SOURCE = REPO / "miniprogram" / "miniprogram_qrcode.jpg"
OUTPUT = REPO / "components" / "brand" / "src" / "brand_qrcode.c"
PREVIEW = REPO / "tools" / "preview_qrcode.png"
PREVIEW_ZOOM = 2


def square_crop(image: Image.Image, bbox: tuple[int, int, int, int]) -> Image.Image:
    """Crop a square around the ink box so the circular code stays centered.

    The green mini program badge sits on the bottom-right corner, so the ink
    box is a few pixels wider than tall; centering the square on the box keeps
    the circle's center on the bitmap's center.
    """
    left, top, right, bottom = bbox
    side = max(right - left, bottom - top)
    cx = (left + right) // 2
    cy = (top + bottom) // 2
    x0 = min(max(0, cx - side // 2), max(0, image.width - side))
    y0 = min(max(0, cy - side // 2), max(0, image.height - side))
    return image.crop((x0, y0, x0 + side, y0 + side))


def load_code(threshold: int) -> Image.Image:
    image = Image.open(SOURCE).convert("L")
    ink = image.point(lambda value: 255 if value < threshold else 0)
    bbox = ink.getbbox()
    if not bbox:
        sys.exit(f"{SOURCE}: no ink found")
    code = square_crop(image, bbox)
    return code.point(lambda value: 0 if value < threshold else 255)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--threshold", type=int, default=INK_THRESHOLD,
                        help="luminance below this becomes ink (default: %(default)s)")
    args = parser.parse_args()
    if not SOURCE.exists():
        sys.exit(f"mini program code not found: {SOURCE}")

    bw = load_code(args.threshold)
    width, height, bits = pack_pixels(bw)

    parts = [
        "/* Generated by tools/gen_qrcode.py from",
        " * miniprogram/miniprogram_qrcode.jpg; do not edit by hand.",
        " *",
        f" * {width}x{height} 1-bit row-major mini program code, MSB first, 1 = ink. */",
        '#include "brand.h"',
        "",
        emit_array("qrcode", bits),
        "",
        f"const brand_bitmap_t brand_qrcode = {{{width}, {height}, k_qrcode_bits}};",
        "",
    ]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(parts))

    bw.resize((width * PREVIEW_ZOOM, height * PREVIEW_ZOOM), Image.NEAREST).save(PREVIEW)
    print(f"wrote {OUTPUT.relative_to(REPO)}")
    print(f"  qrcode: {width}x{height}, {len(bits)} bytes (threshold {args.threshold})")
    print(f"  preview: {PREVIEW.relative_to(REPO)} (zoom {PREVIEW_ZOOM}x)")


if __name__ == "__main__":
    main()
